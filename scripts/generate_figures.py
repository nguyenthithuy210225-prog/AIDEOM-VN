COLORS = {
    "blue": "#2563eb",
    "sky": "#38bdf8",
    "teal": "#0f766e",
    "green": "#16a34a",
    "amber": "#d97706",
    "red": "#dc2626",
    "slate": "#334155",
    "gray": "#94a3b8",
}


FIGURES: list[dict[str, str]] = []


def read_table(name: str) -> pd.DataFrame:
    path = TABLE_DIR / name
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Run `python scripts/generate_outputs.py` first."
        )
    return pd.read_csv(path)


def setup_style() -> None:
    plt.rcParams.update(
        {
            "figure.dpi": 120,
            "savefig.dpi": 220,
            "font.family": "DejaVu Sans",
            "axes.titlesize": 15,
            "axes.titleweight": "bold",
            "axes.labelsize": 11,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "axes.grid": True,
            "grid.alpha": 0.22,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
        }
    )


def save_current(filename: str, title: str, source: str, model: str, note: str) -> None:
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURE_DIR / filename
    plt.tight_layout()
    plt.savefig(path, bbox_inches="tight")
    plt.close()
    FIGURES.append(
        {
            "file": filename,
            "title": title,
            "source": source,
            "model": model,
            "note": note,
        }
    )
    print(path)


def horizontal_bar(
    df: pd.DataFrame,
    x: str,
    y: str,
    title: str,
    xlabel: str,
    filename: str,
    source: str,
    model: str,
    note: str,
    color: str = COLORS["blue"],
) -> None:
    plot_df = df.copy()
    fig, ax = plt.subplots(figsize=(10.5, 5.8))
    ax.barh(plot_df[y], plot_df[x], color=color)
    ax.invert_yaxis()
    ax.set_title(title, loc="left")
    ax.set_xlabel(xlabel)
    ax.set_ylabel("")
    for i, value in enumerate(plot_df[x]):
        ax.text(value, i, f" {value:,.2f}", va="center", fontsize=8)
    save_current(filename, title, source, model, note)


