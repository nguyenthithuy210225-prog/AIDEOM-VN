ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
TABLE_DIR = ROOT / "outputs" / "tables"
FIGURE_DIR = ROOT / "outputs" / "figures"

if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from aideom_vn.config import ensure_output_dirs
