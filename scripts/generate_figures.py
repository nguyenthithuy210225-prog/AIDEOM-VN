"""Generate report-ready PNG figures from the same model outputs used by the app.

The script deliberately avoids hand-entered chart values. Every figure reads from
`outputs/tables/*.csv` generated by `scripts/generate_outputs.py`, except the
Q-learning reward trace which is regenerated with the same default seed used by
the app and output script.
"""

from __future__ import annotations

